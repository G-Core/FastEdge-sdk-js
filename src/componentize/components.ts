import { Buffer } from 'node:buffer';
import { readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { colorLog } from '~utils/color-log.ts';
import { useUnixPath } from '~utils/file-system.ts';
import { importVendored } from '~utils/import-vendored.ts';

/**
 * Wasm components the app imports, keyed by the WIT interface they export
 * (e.g. `{ 'acme:imageopt/optimise': './imageopt.wasm' }`).
 */
type ComponentImports = Record<string, string>;

interface LoadedComponents {
  interfaces: string[];
  binaries: Uint8Array[];
}

interface SpliceResult {
  /** Engine with the import hooks spliced in: the Wizer input. */
  engine: string;
  /** Wizer stdin: the StarlingMonkey arguments. */
  input: string;
  /** Wizer environment for `componentize.wizer`. */
  env: Record<string, string>;
}

interface ComponentTools {
  plug(socket: Uint8Array, plugs: Uint8Array[]): Uint8Array;
  importWorld(components: Uint8Array[], interfaces: string[]): string;
  imports(component: Uint8Array): string[];
}

interface Splicer {
  spliceBindings(
    engine: Uint8Array,
    features: string[],
    witWorld: string | undefined,
    witPath: string | undefined,
    worldName: string | undefined,
    guestTypes: boolean,
  ): {
    wasm: Uint8Array;
    jsBindings: string;
    exports: unknown[];
    imports: Array<[string, string, number]>;
  };
}

// `ns:pkg/iface` or `ns:pkg/iface@1.2.3`
const INTERFACE_NAME = /^[a-z][\da-z-]*:[a-z][\da-z-]*\/[a-z][\da-z-]*(?:@[\w.+-]+)?$/u;

// What the FastEdge host links: WASI 0.2.x (incl. http and nn) and Gcore interfaces.
const ALLOWED_IMPORT = /^(?:wasi:[^@]+@0\.2\.[^@]+|gcore:.+)$/u;

const COMPONENT_TYPES_FILE = 'fastedge-components.d.ts';
const COMPONENT_TYPES_HEADER =
  '// Generated by fastedge-build from the configured components. Do not edit.';

const SPLICE_FEATURES = ['stdio', 'clocks', 'random', 'http', 'fetch-event'];

// The glue runs in its own global, where SpiderMonkey sets up standard classes on first use.
// Touching the ones it uses here, at Wizer time, keeps that out of every request: typed arrays
// and DataView (~160 µs on the first import call), String (~150 µs on the first string
// argument), BigInt (~30 µs on the first u64/s64) and Error (~30 µs on the first `err`).
// See context/development/COMPONENT_PERFORMANCE.md before adding to this.
const GLUE_WARMUP = `
{ const ab = new ArrayBuffer(16);
  new Uint8Array(ab, 0, 4); new Int32Array(ab); new Uint32Array(ab); new Float32Array(ab);
  new Float64Array(ab); new BigInt64Array(ab); new Uint16Array(ab); new Int8Array(ab);
  new Int16Array(ab); new BigUint64Array(ab); new DataView(ab).getUint8(0);
  'a'.charCodeAt(0);
  BigInt.asUintN(64, BigInt(1)); BigInt.asIntN(64, 1n);
  try { throw new Error('warm-up'); } catch {} }
`;

const componentTools = async (): Promise<ComponentTools> =>
  importVendored<ComponentTools>('./vendor/component-tools/component-tools.js');

/**
 * Throws the message of a jco ComponentError (`err` result) rather than `[object Object]`.
 */
function unwrap<T>(fn: () => T): T {
  try {
    return fn();
  } catch (error) {
    const { payload } = error as { payload?: unknown };
    throw new Error(typeof payload === 'string' ? payload : (error as Error).message);
  }
}

/**
 * Validates the interface names and reads each component.
 * @param components - Map of WIT interface name to component path (relative to cwd).
 */
async function loadComponents(components: ComponentImports): Promise<LoadedComponents> {
  const interfaces = Object.keys(components);
  const invalid = interfaces.filter((name) => !INTERFACE_NAME.test(name));
  if (invalid.length > 0) {
    throw new Error(
      `Invalid component interface name: ${invalid.join(', ')} (expected "namespace:package/interface")`,
    );
  }
  // The same file may satisfy several interfaces; plug it once.
  const paths = [...new Set(Object.values(components).map((p) => path.resolve(p)))];
  const tools = await componentTools();
  const binaries = await Promise.all(
    paths.map(async (p) => {
      const bytes = await readFile(p).catch(() => {
        throw new Error(`Component "${p}" is not a readable file`);
      });
      try {
        tools.imports(bytes);
      } catch {
        throw new Error(`"${p}" is not a Wasm component`);
      }
      return bytes;
    }),
  );
  // Composition plugs every matching export, so an interface exported by two of the files
  // cannot be assigned to either; say so instead of failing in composition.
  if (binaries.length > 1) {
    for (const name of interfaces) {
      const exporters = paths.filter((_, i) => {
        try {
          tools.importWorld([binaries[i]], [name]);
          return true;
        } catch {
          return false;
        }
      });
      if (exporters.length > 1) {
        throw new Error(
          `${name} is exported by more than one component: ${exporters.join(', ')}. Components that export the same interface cannot be used together`,
        );
      }
    }
  }
  return { interfaces, binaries };
}

/**
 * WIT text for a world importing `interfaces`, with definitions read from the components.
 */
async function importWorld({ interfaces, binaries }: LoadedComponents): Promise<string> {
  const tools = await componentTools();
  return unwrap(() => tools.importWorld(binaries, interfaces));
}

/**
 * Writes TypeScript declarations (`declare module 'ns:pkg/iface'`) for the imported interfaces.
 * Exits on invalid components, like the other build input checks.
 */
async function writeComponentTypes(
  components: ComponentImports,
  outputPath: string,
): Promise<void> {
  let witWorld;
  try {
    witWorld = await importWorld(await loadComponents(components));
  } catch (error) {
    colorLog('error', `Error: ${(error as Error).message}`);
    process.exit(1);
  }
  const { $init, generateTypes } = await import(
    /* webpackChunkName: "jco-component" */ '@bytecodealliance/jco-transpile/component'
  );
  await $init;
  const files = generateTypes('app', {
    wit: { tag: 'source', val: witWorld },
    world: 'app',
    guest: true,
  });
  const decoder = new TextDecoder();
  const declarations = files
    .filter(([name]) => name.startsWith('interfaces/'))
    .map(([, bytes]) =>
      decoder
        .decode(bytes)
        // All interfaces go in this one file, so drop references to jco's per-interface files
        .replaceAll(/^\/\/\/ <reference path=.*$/gmu, '')
        .replaceAll(/[\t ]+$/gmu, '')
        .trim(),
    );
  await writeFile(outputPath, `${COMPONENT_TYPES_HEADER}\n\n${declarations.join('\n\n')}\n`);
}

/**
 * Deletes declarations left by an earlier build with components, so imports of removed
 * components fail the type check. Leaves any file we did not generate.
 */
async function removeComponentTypes(outputPath: string): Promise<void> {
  const contents = await readFile(outputPath, 'utf8').catch(() => '');
  if (contents.startsWith(COMPONENT_TYPES_HEADER)) {
    await rm(outputPath);
  }
}

const quote = (p: string): string => `"${useUnixPath(p)}"`;

/**
 * Splices the JS import bindings for `witWorld` into the engine, and writes the files
 * `componentize.wizer` loads (bindings + app source) into `tmpDir`.
 */
async function spliceImports(
  wasmEngine: string,
  witWorld: string,
  application: string,
  tmpDir: string,
): Promise<SpliceResult> {
  const { splicer } = await importVendored<{ splicer: Splicer }>(
    './vendor/splicer/spidermonkey-embedding-splicer.js',
  );
  const engineBytes = new Uint8Array(await readFile(wasmEngine));
  const { wasm, jsBindings, exports, imports } = unwrap(() =>
    splicer.spliceBindings(
      engineBytes,
      SPLICE_FEATURES,
      witWorld,
      undefined,
      'app',
      false,
    ),
  );

  const engine = path.join(tmpDir, 'spliced-engine.wasm');
  const initializer = path.join(tmpDir, 'initializer.js');
  const source = path.join(tmpDir, 'source.js');
  await writeFile(engine, wasm);
  await writeFile(initializer, jsBindings + GLUE_WARMUP);
  await writeFile(source, application);

  const env: Record<string, string> = {
    DEBUG: '',
    SOURCE_NAME: 'source.js',
    EXPORT_CNT: String(exports.length),
    FEATURE_CLOCKS: '1',
    IMPORT_CNT: String(imports.length),
  };
  for (const [i, [, name, argCount]] of imports.entries()) {
    env[`IMPORT${i}_NAME`] = name;
    env[`IMPORT${i}_ARGCNT`] = String(argCount);
  }

  // StarlingMonkey splits this on whitespace; quotes keep paths with spaces whole.
  const input = [
    '--initializer-script-path',
    quote(initializer),
    '--strip-path-prefix',
    quote(`${tmpDir}/`),
    quote(source),
  ].join(' ');

  return { engine, input, env };
}

/**
 * Returns the raw bytes (header included) of a module's custom section, or undefined.
 */
function findCustomSection(wasm: Uint8Array, name: string): Uint8Array | undefined {
  // Unsigned LEB128 at `pos`: [value, position after it]
  const leb = (pos: number): [number, number] => {
    let result = 0;
    let shift = 0;
    let p = pos;
    let byte;
    do {
      byte = wasm[p];
      p += 1;
      result += (byte % 0x80) * 2 ** shift;
      shift += 7;
    } while (byte >= 0x80);
    return [result, p];
  };
  const decoder = new TextDecoder();
  let pos = 8; // Magic + version
  while (pos < wasm.length) {
    const start = pos;
    const id = wasm[pos];
    pos += 1;
    const [size, body] = leb(pos);
    pos = body + size;
    if (id === 0) {
      const [nameLength, nameStart] = leb(body);
      if (decoder.decode(wasm.subarray(nameStart, nameStart + nameLength)) === name) {
        return wasm.subarray(start, pos);
      }
    }
  }
  return undefined;
}

/**
 * The splicer replaces the engine's `component-type:bindings` section with one for the
 * imported interfaces only, which drops the FastEdge world (gcore:fastedge imports,
 * http handler export). Appending the engine's original section restores it;
 * `componentNew` merges both.
 */
async function restoreEngineBindings(wasmEngine: string, module: Uint8Array): Promise<Uint8Array> {
  const section = findCustomSection(await readFile(wasmEngine), 'component-type:bindings');
  if (!section) {
    throw new Error(`"${wasmEngine}" has no component-type:bindings section`);
  }
  return Buffer.concat([module, section]);
}

/**
 * Plugs the components into the app's imports, then checks every remaining import is one
 * the FastEdge host provides.
 */
async function composeComponents(
  app: Uint8Array,
  { binaries }: LoadedComponents,
): Promise<Uint8Array> {
  const tools = await componentTools();
  const composed = unwrap(() => tools.plug(app, binaries));
  const unsupported = unwrap(() => tools.imports(composed)).filter(
    (name) => !ALLOWED_IMPORT.test(name),
  );
  if (unsupported.length > 0) {
    throw new Error(
      `Components import interfaces FastEdge does not provide: ${unsupported.join(', ')}`,
    );
  }
  return composed;
}

